// Requires a disposable local PostgreSQL server. Never accepts a remote URL.
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const exec=promisify(execFile);
const port=process.env.RELAY_TEST_PG_PORT || '55432';
if(!/^\d+$/.test(port)) throw Error('Invalid local port');
const db=`relay_audit_${process.pid}`;
const args=['-h','127.0.0.1','-p',port,'-X','-v','ON_ERROR_STOP=1','-At'];
const run=(sql,database=db)=>exec('psql',[...args,'-d',database,'-c',sql],{maxBuffer:4*1024*1024}).then(r=>r.stdout.trim());
const task='00000000-0000-4000-8000-000000000001';
const reset=async(extra='')=>{await run(`truncate public.tasks cascade; insert into public.tasks(id,title,creator_id,creator_name,start_date,end_date) values ('${task}','Fixture','organizer','Fixture','2000-01-01','2099-01-01'); ${extra}`);};
const insert=(owner='owner',extra='')=>`insert into public.signups(task_id,name,owner_token${extra?',created_at':''}) values ('${task}','Fixture','${owner}'${extra?`,${extra}`:''}) returning id;`;
const rejected=async(sql,message)=>{await assert.rejects(run(sql),e=>e.stderr.includes(message));};
let checks=0;
const pass=label=>{checks++;console.log(`PASS ${label}`);};
await run(`create database ${db}`,'postgres');
try {
  await run(`do $$ begin if not exists(select 1 from pg_roles where rolname='anon') then create role anon; end if; if not exists(select 1 from pg_roles where rolname='authenticated') then create role authenticated; end if; if not exists(select 1 from pg_roles where rolname='service_role') then create role service_role bypassrls; end if; end $$;`);
  await run(await readFile('sql/schema.sql','utf8'));
  // Reproduce the original read-then-insert oversubscription against PostgreSQL.
  await reset(`update tasks set max_signups=1 where id='${task}'`);
  const before=await Promise.allSettled(Array.from({length:8},(_,i)=>run(insert(`baseline-${i}`))));
  assert.equal(before.filter(r=>r.status==='fulfilled').length,8);
  console.log('REPRODUCED before migration: 8 registrations admitted for capacity 1');
  await run(await readFile('supabase/migrations/202610280003_signup_integrity.sql','utf8'));
  await reset(`update tasks set max_signups=1 where id='${task}'`);
  const race=await Promise.allSettled(Array.from({length:8},(_,i)=>run(insert(`race-${i}`))));
  assert.equal(race.filter(r=>r.status==='fulfilled').length,1);
  assert.equal(await run('select count(*) from signups'),'1');pass('eight concurrent requests compete for one spot without overbooking');
  await reset(`update tasks set task_mode='queue' where id='${task}'`);
  const duplicate=await Promise.allSettled(Array.from({length:8},()=>run(insert())));
  assert.equal(duplicate.filter(r=>r.status==='fulfilled').length,1);pass('parallel requests from one browser admit only one active queue entry');
  await reset(`update tasks set max_signups=1 where id='${task}'`);
  await rejected(`insert into signups(task_id,name,owner_token,batch_id) values ('${task}','Self','owner','00000000-0000-4000-8000-000000000002'),('${task}','Proxy','owner','00000000-0000-4000-8000-000000000002')`,'額滿');
  assert.equal(await run('select count(*) from signups'),'0');
  await run(`update tasks set max_signups=2`);
  await run(`insert into signups(task_id,name,owner_token,batch_id) values ('${task}','Self','owner','00000000-0000-4000-8000-000000000002'),('${task}','Proxy','owner','00000000-0000-4000-8000-000000000002')`);
  assert.equal(await run('select count(*) from signups'),'2');pass('proxy batches are all-or-nothing and share a cooldown exemption within the batch');
  await reset(`update tasks set max_signups=3,quantity_unit='人'`);
  await run(insert('A'));await run(insert('B'));
  const original=await run("select created_at||'/'||id from signups where owner_token='A'");
  await rejected("update signups set quantity=3 where owner_token='A'",'額滿');
  await run("update signups set name='Renamed',quantity=2 where owner_token='A'");
  assert.equal(await run("select created_at||'/'||id from signups where owner_token='A'"),original);
  await run("delete from signups where owner_token='B'");
  await run("update signups set quantity=3 where owner_token='A'");pass('editing checks total headcount, preserves position, and cancellation frees capacity');
  await reset(`update tasks set task_mode='queue',max_signups=1`);
  await run(insert('same',"now()-interval '31 seconds'"));await run('update signups set checked_in=true');await run(insert('same'));
  await rejected('update signups set checked_in=false where checked_in','已在排隊中');pass('completed entries cannot be reopened over another active entry');
  await reset(`update tasks set end_date='2000-01-01'`);await rejected(insert(),'已截止');
  await run("update tasks set start_date='2099-01-01',end_date='2099-01-02'");await rejected(insert(),'尚未開始');pass('database enforces registration period');
  await reset(`update tasks set task_mode='queue'`);
  await run(`insert into signups(task_id,name,owner_token,created_at) select '${task}','Private '||i,'owner-'||i,now()-interval '60 seconds'+i*interval '1 microsecond' from generate_series(1,1005) i`);
  let snapshot=JSON.parse(await run(`select queue_status_snapshot('${task}','owner-1005')`));
  assert.equal(snapshot.waiting_count,1005);assert.equal(snapshot.queue_number,1005);assert.equal(snapshot.people_ahead,1004);assert.equal(snapshot.my_signups.length,1);
  assert.ok(!JSON.stringify(snapshot).includes('owner-'));assert.equal(snapshot.my_signups[0].name,'Private 1005');
  await run("update signups set checked_in=true where owner_token='owner-1'; delete from signups where owner_token='owner-2'");
  snapshot=JSON.parse(await run(`select queue_status_snapshot('${task}','owner-1005')`));
  assert.equal(snapshot.waiting_count,1003);assert.equal(snapshot.queue_number,1003);assert.equal(snapshot.completed_count,1);pass('snapshot stays accurate above 1000 rows and only returns own name');
  for(const role of ['anon','authenticated']) assert.equal(await run(`select has_function_privilege('${role}','public.queue_status_snapshot(uuid,text)','execute')`),'f');
  assert.equal(await run("select has_function_privilege('service_role','public.queue_status_snapshot(uuid,text)','execute')"),'t');pass('snapshot RPC is unavailable to anonymous and authenticated database roles');
  console.log(`${checks} database integration checks passed`);
} finally {await run(`drop database ${db} with (force)`,'postgres');}
